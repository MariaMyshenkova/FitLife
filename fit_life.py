print("Здравствуйте!")
user_name = input("Как Вас зовут? ")
user_age = input("Сколько Вам лет? ")
user_age = int(user_age)
print('Просим Вас вносить следующие параметры с точкой! Например: 64.3')
user_weight = input("Какой у Вас вес в кг.? ")
user_weight = float(user_weight)
user_height = input("Какой у Вас рост в м.?(например 1.74) ")
user_height = float(user_height)
bmi = round((user_weight / (user_height ** 2)), 1)
water_ml = user_weight * 30
water_l = water_ml / 1000
water_l = round(water_l, 1)
print("\n")
print("-" * 40)
print(f"Отчет для пользователя: {user_name}, {user_age} г.")
print("-" * 40)
print(f"Ваш Индекс Массы Тела: {bmi}")
print(f"Рекомендуемая норма воды: {water_l} л. в день")
print("\n")
print("Расчет окончен. Будьте здоровы!")
